def build_common_geo_grid(meta: pd.DataFrame) -> Dict[str, np.ndarray]:
    lon = np.asarray(normalize_lon_180(pd.to_numeric(meta["lon_180"], errors="coerce").to_numpy(dtype=np.float64)), dtype=np.float64)
    lat = pd.to_numeric(meta["lat"], errors="coerce").to_numpy(dtype=np.float64)
    if not np.isfinite(lon).all() or not np.isfinite(lat).all():
        raise RuntimeError("Cannot build geographic grid from non-finite scenario lon/lat.")
    simple_span = float(np.nanmax(lon) - np.nanmin(lon))
    if simple_span > 180.0:
        lon_min, lon_max = -180.0, 180.0
    else:
        lon_min = math.floor(float(np.nanmin(lon)) - GEO_MARGIN_DEG)
        lon_max = math.ceil(float(np.nanmax(lon)) + GEO_MARGIN_DEG)
        lon_min = max(-180.0, lon_min)
        lon_max = min(180.0, lon_max)
    lat_min = math.floor(float(np.nanmin(lat)) - GEO_MARGIN_DEG)
    lat_max = math.ceil(float(np.nanmax(lat)) + GEO_MARGIN_DEG)
    lat_min = max(-90.0, lat_min)
    lat_max = min(90.0, lat_max)
    if not (lon_min < lon_max and lat_min < lat_max):
        raise RuntimeError(f"Invalid common geographic bounds: lon=({lon_min},{lon_max}), lat=({lat_min},{lat_max})")
    lon_1d = np.round(np.arange(lon_min, lon_max + GEO_RES_DEG * 0.5, GEO_RES_DEG), 6).astype(np.float64)
    lat_1d = np.round(np.arange(lat_min, lat_max + GEO_RES_DEG * 0.5, GEO_RES_DEG), 6).astype(np.float64)
    lon_1d = np.asarray(normalize_lon_180(lon_1d), dtype=np.float64)
    lon2d, lat2d = np.meshgrid(lon_1d, lat_1d)
    area_1d = EARTH_KM_PER_DEG * GEO_RES_DEG * EARTH_KM_PER_DEG * GEO_RES_DEG * np.cos(np.deg2rad(lat_1d))
    area_1d = np.maximum(area_1d, 0.0).astype(np.float64)
    area_2d = np.repeat(area_1d[:, None], len(lon_1d), axis=1)
    return {
        "lon_1d": lon_1d,
        "lat_1d": lat_1d,
        "lon2d": lon2d,
        "lat2d": lat2d,
        "area_1d": area_1d,
        "area_2d": area_2d,
    }


def backproject_scenarios(
    rain: np.ndarray,
    meta: pd.DataFrame,
    x_front_km: np.ndarray,
    y_left_km: np.ndarray,
    geo: Mapping[str, np.ndarray],
    problem2_geo_module,
) -> Tuple[Dict[str, Dict[str, object]], pd.DataFrame]:
    lon_1d = np.asarray(geo["lon_1d"], dtype=np.float64)
    lat_1d = np.asarray(geo["lat_1d"], dtype=np.float64)
    lon2d = np.asarray(geo["lon2d"], dtype=np.float64)
    lat2d = np.asarray(geo["lat2d"], dtype=np.float64)
    area_1d = np.asarray(geo["area_1d"], dtype=np.float64)
    shape = lon2d.shape

    results: Dict[str, Dict[str, object]] = {}
    timeseries_rows: List[Dict[str, object]] = []

    for sid in SCENARIO_ORDER:
        sub = meta.loc[meta["scenario_id"] == sid].copy()
        if sub.empty:
            raise RuntimeError(f"Missing scenario rows for {sid}")
        sub = sub.sort_values("time_dt").reset_index(drop=True)
        scenario_name = str(sub["scenario_name"].iloc[0])
        cumulative = np.zeros(shape, dtype=np.float64)
        duration10 = np.zeros(shape, dtype=np.float32)
        duration20 = np.zeros(shape, dtype=np.float32)
        max_rate = np.zeros(shape, dtype=np.float32)
        qc = {"nan": 0, "inf": 0, "negative": 0, "all_zero_timeslices": 0, "sampled_points_total": 0}

        for _, row in iter_progress(list(sub.iterrows()), total=len(sub), desc=f"Backproject {sid}"):
            field_index = int(row["field_index"])
            r_geo, step_qc = problem2_geo_module.sample_storm_relative_to_geo_grid(
                rain[field_index],
                x_front_km,
                y_left_km,
                float(row["lon_180"]),
                float(row["lat"]),
                float(row["move_dir_deg"]),
                lon2d,
                lat2d,
            )
            r_geo = np.nan_to_num(r_geo, nan=0.0, posinf=0.0, neginf=0.0).astype(np.float32)
            r_geo = np.maximum(r_geo, 0.0)
            for key in ["nan", "inf", "negative"]:
                qc[key] += int(step_qc.get(key, 0))
            qc["sampled_points_total"] += int(step_qc.get("sampled_points", 0))
            if not np.any(r_geo > 0.0):
                qc["all_zero_timeslices"] += 1

            cumulative += r_geo.astype(np.float64) * HALFHOUR_HOURS
            duration10 += (r_geo >= AREA10_THRESHOLD).astype(np.float32) * HALFHOUR_HOURS
            duration20 += (r_geo >= AREA20_THRESHOLD).astype(np.float32) * HALFHOUR_HOURS
            max_rate = np.maximum(max_rate, r_geo)

            step_max, step_lon, step_lat = argmax_lon_lat(r_geo, lon_1d, lat_1d)
            timeseries_rows.append(
                {
                    "scenario_id": sid,
                    "scenario_name": scenario_name,
                    "time": pd.Timestamp(row["time_dt"]).strftime("%Y-%m-%d %H:%M:%S"),
                    "field_index": field_index,
                    "lat": float(row["lat"]),
                    "lon": float(row["lon"]),
                    "lon_180": float(row["lon_180"]),
                    "WND": float(row["WND"]),
                    "PRES": float(row["PRES"]),
                    "move_dir_deg": float(row["move_dir_deg"]),
                    "geo_rain_max_mmhr": float(step_max),
                    "geo_area10_km2": area_of_mask(r_geo >= AREA10_THRESHOLD, area_1d),
                    "geo_area20_km2": area_of_mask(r_geo >= AREA20_THRESHOLD, area_1d),
                    "geo_volume_index_halfhour_mm_km2": weighted_field_sum(r_geo * HALFHOUR_HOURS, area_1d),
                    "geo_max_rain_lon": float(step_lon),
                    "geo_max_rain_lat": float(step_lat),
                }
            )

        results[sid] = {
            "scenario_id": sid,
            "scenario_name": scenario_name,
            "track": sub,
            "accum_rain_mm": cumulative.astype(np.float32),
            "duration10_h": duration10.astype(np.float32),
            "duration20_h": duration20.astype(np.float32),
            "max_rate_mmhr": max_rate.astype(np.float32),
            "qc": qc,
        }

    return results, pd.DataFrame(timeseries_rows)


def grid_lookup_indices(source_1d: np.ndarray, target_1d: np.ndarray, axis_name: str) -> np.ndarray:
    lookup = {round(float(value), 6): i for i, value in enumerate(np.asarray(target_1d, dtype=np.float64))}
    indices: List[int] = []
    missing: List[float] = []
    for value in np.asarray(source_1d, dtype=np.float64):
        key = round(float(value), 6)
        if key not in lookup:
            missing.append(float(value))
        else:
            indices.append(int(lookup[key]))
    if missing:
        preview = ", ".join(f"{v:.6f}" for v in missing[:5])
        raise RuntimeError(f"Problem-2 KONG-REY {axis_name} grid cannot be embedded in Problem-3 common grid; missing: {preview}")
    return np.asarray(indices, dtype=int)


def embed_problem2_field(
    p2_field: np.ndarray,
    p2_lon_1d: np.ndarray,
    p2_lat_1d: np.ndarray,
    geo: Mapping[str, np.ndarray],
) -> np.ndarray:
    out = np.zeros(np.asarray(geo["lon2d"]).shape, dtype=np.float32)
    iy = grid_lookup_indices(p2_lat_1d, np.asarray(geo["lat_1d"], dtype=np.float64), "latitude")
    ix = grid_lookup_indices(p2_lon_1d, np.asarray(geo["lon_1d"], dtype=np.float64), "longitude")
    arr = np.asarray(p2_field, dtype=np.float32)
    if arr.shape != (len(iy), len(ix)):
        raise RuntimeError(f"Problem-2 KONG-REY geographic field shape {arr.shape} does not match lon/lat axes {(len(iy), len(ix))}.")
    out[np.ix_(iy, ix)] = arr
    return out


def reuse_problem2_kongrey_geographic_baseline(
    results: Dict[str, Dict[str, object]],
    geo: Mapping[str, np.ndarray],
    geo_timeseries: pd.DataFrame,
) -> Tuple[Dict[str, Dict[str, object]], pd.DataFrame, Dict[str, object]]:
    info: Dict[str, object] = {
        "status": "not_checked",
        "note": "Problem-2 KONG-REY geographic baseline was not reused.",
    }
    if not (PROBLEM2_GEO_NPZ_PATH.exists() and PROBLEM2_GEO_TIMESERIES_PATH.exists()):
        info["status"] = "missing"
        info["note"] = "Problem-2 KONG-REY geographic NPZ or timeseries table is missing."
        return results, geo_timeseries, info

    with np.load(PROBLEM2_GEO_NPZ_PATH, allow_pickle=True) as z:
        required = [
            "KONG_REY_geo_lon_1d",
            "KONG_REY_geo_lat_1d",
            "KONG_REY_geo_cumulative_rain_mm",
            "KONG_REY_geo_max_rain_mmhr",
            "KONG_REY_geo_duration10_h",
            "KONG_REY_geo_duration20_h",
        ]
        missing = [key for key in required if key not in z.files]
        if missing:
            raise RuntimeError(f"Problem-2 KONG-REY geographic NPZ missing arrays: {missing}")
        p2_lon = np.asarray(z["KONG_REY_geo_lon_1d"], dtype=np.float64)
        p2_lat = np.asarray(z["KONG_REY_geo_lat_1d"], dtype=np.float64)
        accum = embed_problem2_field(z["KONG_REY_geo_cumulative_rain_mm"], p2_lon, p2_lat, geo)
        max_rate = embed_problem2_field(z["KONG_REY_geo_max_rain_mmhr"], p2_lon, p2_lat, geo)
        d10 = embed_problem2_field(z["KONG_REY_geo_duration10_h"], p2_lon, p2_lat, geo)
        d20 = embed_problem2_field(z["KONG_REY_geo_duration20_h"], p2_lon, p2_lat, geo)

    p2_ts = pd.read_csv(PROBLEM2_GEO_TIMESERIES_PATH)
    p2_ts = p2_ts.loc[p2_ts["typhoon_name"].astype(str).eq("KONG-REY")].copy()
    p2_ts["time_dt"] = pd.to_datetime(p2_ts["time"], errors="coerce")
    s0_track = results["S0"]["track"].copy()
    s0_track["time_dt"] = pd.to_datetime(s0_track["time_dt"], errors="coerce")
    if len(p2_ts) != len(s0_track):
        info["status"] = "failed"
        info["note"] = f"Problem-2 KONG-REY geographic rows={len(p2_ts)}, S0 rows={len(s0_track)}."
        return results, geo_timeseries, info
    p2_times = p2_ts.sort_values("time_dt")["time_dt"].astype("int64").to_numpy()
    s0_times = s0_track.sort_values("time_dt")["time_dt"].astype("int64").to_numpy()
    if not np.array_equal(p2_times, s0_times):
        info["status"] = "failed"
        info["note"] = "Problem-2 KONG-REY geographic times do not match Problem-3 S0 times."
        return results, geo_timeseries, info

    s0_meta = s0_track.sort_values("time_dt").reset_index(drop=True)
    p2_ts = p2_ts.sort_values("time_dt").reset_index(drop=True)
    s0_geo_rows = pd.DataFrame(
        {
            "scenario_id": "S0",
            "scenario_name": str(results["S0"]["scenario_name"]),
            "time": s0_meta["time_dt"].dt.strftime("%Y-%m-%d %H:%M:%S"),
            "field_index": pd.to_numeric(s0_meta["field_index"], errors="coerce").astype(int),
            "lat": pd.to_numeric(s0_meta["lat"], errors="coerce"),
            "lon": pd.to_numeric(s0_meta["lon"], errors="coerce"),
            "lon_180": pd.to_numeric(s0_meta["lon_180"], errors="coerce"),
            "WND": pd.to_numeric(s0_meta["WND"], errors="coerce"),
            "PRES": pd.to_numeric(s0_meta["PRES"], errors="coerce"),
            "move_dir_deg": pd.to_numeric(s0_meta["move_dir_deg"], errors="coerce"),
            "geo_rain_max_mmhr": pd.to_numeric(p2_ts["geo_rain_max_mmhr"], errors="coerce"),
            "geo_area10_km2": pd.to_numeric(p2_ts["geo_area_10_km2"], errors="coerce"),
            "geo_area20_km2": pd.to_numeric(p2_ts["geo_area_20_km2"], errors="coerce"),
            "geo_volume_index_halfhour_mm_km2": pd.to_numeric(p2_ts["geo_volume_proxy_mm_km2"], errors="coerce"),
            "geo_max_rain_lon": pd.to_numeric(p2_ts["geo_max_rain_lon"], errors="coerce"),
            "geo_max_rain_lat": pd.to_numeric(p2_ts["geo_max_rain_lat"], errors="coerce"),
        }
    )

    updated = dict(results)
    updated["S0"] = {
        **results["S0"],
        "accum_rain_mm": accum,
        "duration10_h": d10,
        "duration20_h": d20,
        "max_rate_mmhr": max_rate,
        "qc": {
            "nan": 0,
            "inf": 0,
            "negative": 0,
            "all_zero_timeslices": 0,
            "sampled_points_total": 0,
            "source": "problem2_kongrey_geographic_baseline",
        },
    }
    out_ts = pd.concat([s0_geo_rows, geo_timeseries.loc[geo_timeseries["scenario_id"] != "S0"].copy()], ignore_index=True)
    out_ts["time"] = pd.to_datetime(out_ts["time"], errors="coerce").dt.strftime("%Y-%m-%d %H:%M:%S")
    info.update(
        {
            "status": "reused",
            "note": "S0 geographic accumulation, max rain, D10/D20 and A10/A20 timeseries directly reuse Problem-2 KONG-REY geographic baseline.",
            "reused_timesteps": int(len(s0_geo_rows)),
            "embedded_shape": str(tuple(accum.shape)),
        }
    )
    return updated, out_ts, info


