def load_inputs() -> Dict[str, object]:
    for path in [
        SCENARIO_INPUT_PATH,
        SCENARIO_SUMMARY_PATH,
        CALIBRATED_NPZ_PATH,
        TIMESLICE_METRICS_PATH,
        GENERATION_QC_PATH,
        TOPK_PATH,
        PROBLEM2_EOF_MODEL_PATH,
    ]:
        require_file(path)

    with np.load(CALIBRATED_NPZ_PATH, allow_pickle=True) as z:
        required = ["rainfields_calibrated_mmhr", "scenario_id", "scenario_name", "time", "lat", "lon", "lon_180", "WND", "PRES"]
        missing = [key for key in required if key not in z.files]
        if missing:
            raise RuntimeError(f"Problem-3 calibrated NPZ missing required arrays: {missing}")
        rain = np.asarray(z["rainfields_calibrated_mmhr"], dtype=np.float32)
        meta = {key: z[key] for key in required if key != "rainfields_calibrated_mmhr"}

    if rain.ndim != 3 or rain.shape[1:] != (201, 201):
        raise RuntimeError(f"Unexpected calibrated rainfield shape: {rain.shape}")
    if len(meta["scenario_id"]) != rain.shape[0]:
        raise RuntimeError("Calibrated rainfield time dimension and metadata length mismatch.")
    if np.isnan(rain).any() or np.isinf(rain).any() or np.any(rain < 0.0):
        raise RuntimeError("Calibrated rainfields contain NaN, Inf, or negative values.")

    with np.load(PROBLEM2_EOF_MODEL_PATH, allow_pickle=True) as z:
        if "x_front_km" not in z.files or "y_left_km" not in z.files:
            raise RuntimeError("Problem-2 EOF/PCA model artifact lacks x_front_km/y_left_km grid axes.")
        x_front_km = np.asarray(z["x_front_km"], dtype=np.float64)
        y_left_km = np.asarray(z["y_left_km"], dtype=np.float64)

    npz_meta = pd.DataFrame(
        {
            "field_index": np.arange(rain.shape[0], dtype=int),
            "scenario_id": np.asarray(meta["scenario_id"]).astype(str),
            "scenario_name": np.asarray(meta["scenario_name"]).astype(str),
            "time": np.asarray(meta["time"]).astype(str),
            "lat_npz": np.asarray(meta["lat"], dtype=float),
            "lon_npz": np.asarray(meta["lon"], dtype=float),
            "lon_180_npz": np.asarray(meta["lon_180"], dtype=float),
            "WND_npz": np.asarray(meta["WND"], dtype=float),
            "PRES_npz": np.asarray(meta["PRES"], dtype=float),
        }
    )
    npz_meta["time_dt"] = pd.to_datetime(npz_meta["time"], errors="coerce")
    if npz_meta["time_dt"].isna().any():
        raise RuntimeError("Calibrated NPZ metadata contains unparseable time values.")

    scenario_inputs = pd.read_csv(SCENARIO_INPUT_PATH)
    scenario_inputs["time"] = pd.to_datetime(scenario_inputs["time"], errors="coerce").dt.strftime("%Y-%m-%d %H:%M:%S")
    scenario_inputs["scenario_id"] = scenario_inputs["scenario_id"].astype(str)
    scenario_inputs["lon_180"] = normalize_lon_180(pd.to_numeric(scenario_inputs["lon"], errors="coerce").to_numpy(dtype=np.float64))
    needed = ["scenario_id", "scenario_name", "time", "lat", "lon", "lon_180", "WND", "PRES", "move_dir_deg"]
    missing_cols = [col for col in needed if col not in scenario_inputs.columns]
    if missing_cols:
        raise RuntimeError(f"Scenario input table missing required columns for geographic backprojection: {missing_cols}")

    canonical = npz_meta.merge(
        scenario_inputs[needed],
        on=["scenario_id", "scenario_name", "time"],
        how="left",
        validate="one_to_one",
    )
    if canonical["move_dir_deg"].isna().any():
        missing = canonical.loc[canonical["move_dir_deg"].isna(), ["scenario_id", "time"]].head()
        raise RuntimeError(f"Unable to align NPZ metadata with scenario_inputs for move_dir_deg. Examples: {missing.to_dict('records')}")
    canonical["lat"] = pd.to_numeric(canonical["lat"], errors="coerce")
    canonical["lon"] = pd.to_numeric(canonical["lon"], errors="coerce")
    canonical["lon_180"] = normalize_lon_180(pd.to_numeric(canonical["lon"], errors="coerce").to_numpy(dtype=np.float64))
    canonical["WND"] = pd.to_numeric(canonical["WND"], errors="coerce")
    canonical["PRES"] = pd.to_numeric(canonical["PRES"], errors="coerce")
    canonical["move_dir_deg"] = pd.to_numeric(canonical["move_dir_deg"], errors="coerce")
    if canonical[["lat", "lon_180", "move_dir_deg"]].isna().any().any():
        raise RuntimeError("Canonical scenario metadata has missing lat/lon_180/move_dir_deg values.")

    timeslice_metrics = pd.read_csv(TIMESLICE_METRICS_PATH)
    generation_qc = pd.read_csv(GENERATION_QC_PATH)
    scenario_summary = pd.read_csv(SCENARIO_SUMMARY_PATH)
    topk = pd.read_csv(TOPK_PATH, usecols=["scenario_id", "analog_distance"])

    return {
        "rain": rain,
        "x_front_km": x_front_km,
        "y_left_km": y_left_km,
        "meta": canonical,
        "timeslice_metrics": timeslice_metrics,
        "generation_qc": generation_qc,
        "scenario_summary": scenario_summary,
        "topk": topk,
        "scenario_inputs": scenario_inputs,
    }


