def summarize_topk(topk: pd.DataFrame) -> pd.DataFrame:
    return (
        topk.assign(analog_distance=pd.to_numeric(topk["analog_distance"], errors="coerce"))
        .groupby("scenario_id", as_index=False)
        .agg(
            mean_topk_distance=("analog_distance", "mean"),
            p95_topk_distance=("analog_distance", lambda s: float(np.nanpercentile(s, 95))),
        )
    )


def compute_event_metrics(
    results: Mapping[str, Mapping[str, object]],
    geo: Mapping[str, np.ndarray],
    geo_timeseries: pd.DataFrame,
    timeslice_metrics: pd.DataFrame,
    topk_summary: pd.DataFrame,
) -> pd.DataFrame:
    lon_1d = np.asarray(geo["lon_1d"], dtype=np.float64)
    lat_1d = np.asarray(geo["lat_1d"], dtype=np.float64)
    lon2d = np.asarray(geo["lon2d"], dtype=np.float64)
    lat2d = np.asarray(geo["lat2d"], dtype=np.float64)
    area_1d = np.asarray(geo["area_1d"], dtype=np.float64)
    topk_by_sid = topk_summary.set_index("scenario_id").to_dict("index")

    base_accum = np.asarray(results["S0"]["accum_rain_mm"], dtype=np.float64)
    base_d10 = np.asarray(results["S0"]["duration10_h"], dtype=np.float64)
    base_centroid_lon, base_centroid_lat = rainfall_centroid(base_accum, lon2d, lat2d, area_1d)
    base_mask_acc100 = base_accum >= 100.0
    base_mask_d10_3h = base_d10 >= 3.0

    rows: List[Dict[str, object]] = []
    for sid in SCENARIO_ORDER:
        result = results[sid]
        name = str(result["scenario_name"])
        sub_track = result["track"].copy()
        sub_geo_ts = geo_timeseries.loc[geo_timeseries["scenario_id"] == sid].copy()
        sub_slice = timeslice_metrics.loc[timeslice_metrics["scenario_id"].astype(str) == sid].copy()
        accum = np.asarray(result["accum_rain_mm"], dtype=np.float64)
        d10 = np.asarray(result["duration10_h"], dtype=np.float64)
        d20 = np.asarray(result["duration20_h"], dtype=np.float64)
        max_rate_field = np.asarray(result["max_rate_mmhr"], dtype=np.float64)
        max_accum, max_lon, max_lat = argmax_lon_lat(accum, lon_1d, lat_1d)
        max_rate, _, _ = argmax_lon_lat(max_rate_field, lon_1d, lat_1d)
        centroid_lon, centroid_lat = rainfall_centroid(accum, lon2d, lat2d, area_1d)
        centroid_shift = 0.0 if sid == "S0" else haversine_km(base_centroid_lon, base_centroid_lat, centroid_lon, centroid_lat)
        topk_row = topk_by_sid.get(sid, {})
        row = {
            "scenario_id": sid,
            "scenario_name": name,
            "n_timesteps": int(len(sub_track)),
            "start_time": pd.Timestamp(sub_track["time_dt"].min()).strftime("%Y-%m-%d %H:%M:%S"),
            "end_time": pd.Timestamp(sub_track["time_dt"].max()).strftime("%Y-%m-%d %H:%M:%S"),
            "max_accum_rain_mm": float(max_accum),
            "max_accum_lon": float(max_lon),
            "max_accum_lat": float(max_lat),
            "max_rain_rate_mmhr": float(max_rate),
            "max_p95_mmhr": float(pd.to_numeric(sub_slice["p95_mmhr"], errors="coerce").max()),
            "max_p99_mmhr": float(pd.to_numeric(sub_slice["p99_mmhr"], errors="coerce").max()),
            "max_area10_km2": float(pd.to_numeric(sub_geo_ts["geo_area10_km2"], errors="coerce").max()),
            "max_area20_km2": float(pd.to_numeric(sub_geo_ts["geo_area20_km2"], errors="coerce").max()),
            "mean_area10_km2": float(pd.to_numeric(sub_geo_ts["geo_area10_km2"], errors="coerce").mean()),
            "mean_area20_km2": float(pd.to_numeric(sub_geo_ts["geo_area20_km2"], errors="coerce").mean()),
            "geo_D10_max_h": float(np.nanmax(d10)),
            "geo_D20_max_h": float(np.nanmax(d20)),
            "area_accum_ge_100mm_km2": area_of_mask(accum >= 100.0, area_1d),
            "area_accum_ge_250mm_km2": area_of_mask(accum >= 250.0, area_1d),
            "area_D10_ge_3h_km2": area_of_mask(d10 >= 3.0, area_1d),
            "area_D10_ge_6h_km2": area_of_mask(d10 >= 6.0, area_1d),
            "rainfall_centroid_lon": float(centroid_lon),
            "rainfall_centroid_lat": float(centroid_lat),
            "rainfall_centroid_shift_km_vs_S0": float(centroid_shift),
            "IoU_accum_ge_100mm_vs_S0": 1.0 if sid == "S0" else weighted_iou(accum >= 100.0, base_mask_acc100, area_1d),
            "IoU_D10_ge_3h_vs_S0": 1.0 if sid == "S0" else weighted_iou(d10 >= 3.0, base_mask_d10_3h, area_1d),
            "total_event_rain_volume_index": weighted_field_sum(accum, area_1d),
            "dominant_quadrant_mode": dominant_mode(sub_slice.get("dominant_quadrant", pd.Series(dtype=str))),
            "mean_topk_distance": float(topk_row.get("mean_topk_distance", np.nan)),
            "p95_topk_distance": float(topk_row.get("p95_topk_distance", np.nan)),
            "qc_level": "PENDING",
            "interpretation_note": "",
        }
        rows.append(row)
    metrics = pd.DataFrame(rows)
    return metrics


