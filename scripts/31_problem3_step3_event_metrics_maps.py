def normalize_lon_180(lon: object) -> object:
    arr = np.asarray(lon, dtype=np.float64)
    out = ((arr + 180.0) % 360.0) - 180.0
    out = np.where(np.isclose(out, -180.0) & (arr > 0.0), 180.0, out)
    if np.isscalar(lon):
        return float(out)
    return out


def lon_diff_deg(lon: np.ndarray, center_lon: float) -> np.ndarray:
    return np.asarray(normalize_lon_180(lon - center_lon), dtype=np.float64)


def haversine_km(lon1: float, lat1: float, lon2: float, lat2: float) -> float:
    if not all(np.isfinite([lon1, lat1, lon2, lat2])):
        return float("nan")
    lat1_rad = math.radians(float(lat1))
    lat2_rad = math.radians(float(lat2))
    dlat = lat2_rad - lat1_rad
    dlon = math.radians(float(lon_diff_deg(np.asarray([lon2], dtype=float), float(lon1))[0]))
    a = math.sin(dlat / 2.0) ** 2 + math.cos(lat1_rad) * math.cos(lat2_rad) * math.sin(dlon / 2.0) ** 2
    return float(6371.0 * 2.0 * math.asin(math.sqrt(max(0.0, min(1.0, a)))))


def area_of_mask(mask: np.ndarray, cell_area_1d: np.ndarray) -> float:
    valid = np.asarray(mask, dtype=bool)
    row_counts = np.count_nonzero(valid, axis=1).astype(np.float64)
    return float(np.sum(row_counts * np.asarray(cell_area_1d, dtype=np.float64)))


def weighted_field_sum(field: np.ndarray, cell_area_1d: np.ndarray) -> float:
    arr = np.nan_to_num(np.asarray(field, dtype=np.float64), nan=0.0, posinf=0.0, neginf=0.0)
    return float(np.sum(arr * np.asarray(cell_area_1d, dtype=np.float64)[:, None]))


def argmax_lon_lat(field: np.ndarray, lon_1d: np.ndarray, lat_1d: np.ndarray) -> Tuple[float, float, float]:
    arr = np.asarray(field, dtype=np.float64)
    if arr.size == 0 or not np.isfinite(arr).any():
        return np.nan, np.nan, np.nan
    clean = np.where(np.isfinite(arr), arr, -np.inf)
    iy, ix = np.unravel_index(int(np.argmax(clean)), clean.shape)
    return float(clean[iy, ix]), float(lon_1d[ix]), float(lat_1d[iy])


def pct_change(value: float, base: float) -> float:
    if not np.isfinite(base) or abs(float(base)) < EPS:
        return float("nan")
    if not np.isfinite(value):
        return float("nan")
    return float(100.0 * (float(value) - float(base)) / float(base))


def weighted_iou(mask: np.ndarray, base_mask: np.ndarray, cell_area_1d: np.ndarray) -> float:
    a = np.asarray(mask, dtype=bool)
    b = np.asarray(base_mask, dtype=bool)
    inter = area_of_mask(a & b, cell_area_1d)
    union = area_of_mask(a | b, cell_area_1d)
    if union <= 0.0:
        return float("nan")
    return float(inter / union)


def rainfall_centroid(
    field: np.ndarray,
    lon2d: np.ndarray,
    lat2d: np.ndarray,
    cell_area_1d: np.ndarray,
) -> Tuple[float, float]:
    arr = np.nan_to_num(np.asarray(field, dtype=np.float64), nan=0.0, posinf=0.0, neginf=0.0)
    weights = arr * np.asarray(cell_area_1d, dtype=np.float64)[:, None]
    total = float(np.sum(weights))
    if total <= 0.0:
        return float("nan"), float("nan")
    lon = float(np.sum(np.asarray(lon2d, dtype=np.float64) * weights) / total)
    lat = float(np.sum(np.asarray(lat2d, dtype=np.float64) * weights) / total)
    return lon, lat


def markdown_table(df: pd.DataFrame, columns: Optional[Sequence[str]] = None, max_rows: Optional[int] = None) -> str:
    view = df.copy()
    if columns is not None:
        view = view[list(columns)]
    if max_rows is not None:
        view = view.head(max_rows)
    if view.empty:
        return "_Empty table._"
    out = []
    header = "| " + " | ".join(map(str, view.columns)) + " |"
    sep = "| " + " | ".join(["---"] * len(view.columns)) + " |"
    out.extend([header, sep])
    for _, row in view.iterrows():
        vals = []
        for val in row:
            if isinstance(val, float):
                vals.append("" if pd.isna(val) else f"{val:.3f}")
            else:
                vals.append(str(val))
        out.append("| " + " | ".join(vals) + " |")
    return "\n".join(out)


def dominant_mode(series: pd.Series) -> str:
    if series.empty:
        return "NA"
    counts = series.dropna().astype(str).value_counts()
    if counts.empty:
        return "NA"
    return str(counts.index[0])


