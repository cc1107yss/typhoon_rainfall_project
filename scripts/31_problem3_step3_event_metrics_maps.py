def main() -> None:
    ensure_dirs()
    problem2_geo_module = load_problem2_geo_module()

    print("[31] Loading Problem-3 Step-2 rainfields and metadata")
    inputs = load_inputs()
    rain = np.asarray(inputs["rain"], dtype=np.float32)
    meta = inputs["meta"].copy()
    print(f"[31] Calibrated rainfield shape: {rain.shape}")

    counts = meta.groupby("scenario_id").size().reindex(SCENARIO_ORDER).fillna(0).astype(int)
    for sid, expected in EXPECTED_COUNTS.items():
        actual = int(counts.loc[sid])
        if actual != expected:
            raise RuntimeError(f"{sid} timestep count mismatch: actual={actual}, expected={expected}")

    print("[31] Building common geographic grid and backprojecting S0-S5")
    geo = build_common_geo_grid(meta)
    results, geo_timeseries = backproject_scenarios(
        rain,
        meta,
        np.asarray(inputs["x_front_km"], dtype=np.float64),
        np.asarray(inputs["y_left_km"], dtype=np.float64),
        geo,
        problem2_geo_module,
    )
    results, geo_timeseries, geo_reuse = reuse_problem2_kongrey_geographic_baseline(results, geo, geo_timeseries)
    print(f"[31] S0 geographic baseline reuse: {geo_reuse['status']} - {geo_reuse['note']}")

    print("[31] Computing event metrics and relative changes")
    topk_summary = summarize_topk(inputs["topk"])
    metrics = compute_event_metrics(results, geo, geo_timeseries, inputs["timeslice_metrics"], topk_summary)
    rel_changes = make_relative_changes(metrics)
    baseline = compare_s0_with_problem2_baseline(metrics)

    print("[31] Saving geographic arrays and drawing figures")
    save_geographic_npz(results, geo)
    geo_timeseries.to_csv(GEOGRAPHIC_TIMESERIES_PATH, index=False)
    use_cartopy = cartopy_available(problem2_geo_module)
    figure_paths: List[Path] = []
    figure_paths.extend(make_map_figures(results, metrics, geo, problem2_geo_module))
    figure_paths.extend(make_metric_bar_figures(metrics, rel_changes, results, geo, problem2_geo_module))

    print("[31] Building QC, comparison tables, and report")
    qc = build_step3_qc(results, geo, inputs["generation_qc"], baseline, figure_paths)
    metrics = add_interpretation_and_qc(metrics, qc, rel_changes)
    rel_changes = make_relative_changes(metrics)
    comparison, sensitivity = make_final_and_sensitivity_tables(metrics, rel_changes)

    metrics.to_csv(EVENT_METRICS_PATH, index=False)
    rel_changes.to_csv(RELATIVE_CHANGES_PATH, index=False)
    qc.to_csv(STEP3_QC_PATH, index=False)
    comparison.to_csv(FINAL_COMPARISON_TABLE_PATH, index=False)
    sensitivity.to_csv(SENSITIVITY_TABLE_PATH, index=False)
    write_problem3_latex_tables(comparison)

    final_status = "SUCCESS"
    if (qc["qc_level"] == "FAIL").any():
        final_status = "FAIL"
    elif (qc["qc_level"] == "WARNING").any():
        final_status = "WARNING"

    write_report(
        inputs,
        geo,
        metrics,
        rel_changes,
        comparison,
        sensitivity,
        qc,
        baseline,
        figure_paths,
        use_cartopy,
        final_status,
    )

    print("\n========== Problem-3 Step-3 event metrics complete ==========")
    print(f"Calibrated rainfield shape: {rain.shape}")
    print(f"Scenario IDs: {SCENARIO_ORDER}")
    print("Scenario timesteps:")
    print(counts.to_string())
    print(f"0.5-hour accumulation conversion applied: True")
    print(f"Geographic backprojection applied: True")
    print(f"Event metrics output: {rel(EVENT_METRICS_PATH)}")
    print(f"Relative changes output: {rel(RELATIVE_CHANGES_PATH)}")
    print(f"Geographic NPZ output: {rel(GEOGRAPHIC_NPZ_PATH)}")
    print(f"Final comparison table output: {rel(FINAL_COMPARISON_TABLE_PATH)}")
    print(f"Compact LaTeX table output: {rel(COMPACT_MAIN_TABLE_PATH)}")
    print(f"Figures generated: {len(figure_paths)}")
    print(f"Report output: {rel(REPORT_PATH)}")
    print("Per-scenario QC level:")
    print(qc[["scenario_id", "qc_level", "qc_note"]].to_string(index=False))
    print(f"Final status: {final_status}")


if __name__ == "__main__":
    main()
