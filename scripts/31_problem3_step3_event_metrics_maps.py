def compare_s0_with_problem2_baseline(metrics: pd.DataFrame) -> Dict[str, object]:
    out = {
        "status": "not_found",
        "note": "Problem-2 geographic baseline files were not found.",
        "problem2_max_accum_rain_mm": np.nan,
        "problem3_s0_max_accum_rain_mm": np.nan,
        "max_accum_abs_diff_mm": np.nan,
        "max_accum_location_shift_km": np.nan,
        "problem2_geo_D10_max_h": np.nan,
        "problem3_s0_geo_D10_max_h": np.nan,
        "geo_D10_abs_diff_h": np.nan,
        "problem2_max_area10_km2": np.nan,
        "problem3_s0_max_area10_km2": np.nan,
        "max_area10_rel_diff_pct": np.nan,
        "problem2_volume_index": np.nan,
        "problem3_s0_volume_index": np.nan,
        "volume_rel_diff_pct": np.nan,
    }
    if not (PROBLEM2_GEO_SUMMARY_PATH.exists() and PROBLEM2_GEO_TIMESERIES_PATH.exists()):
        return out
    p2_summary = pd.read_csv(PROBLEM2_GEO_SUMMARY_PATH)
    p2_ts = pd.read_csv(PROBLEM2_GEO_TIMESERIES_PATH)
    p2_row = p2_summary.loc[p2_summary["typhoon_name"].astype(str).eq("KONG-REY")]
    p2_ts = p2_ts.loc[p2_ts["typhoon_name"].astype(str).eq("KONG-REY")]
    if p2_row.empty or p2_ts.empty:
        out["note"] = "Problem-2 geographic files exist, but KONG-REY rows were not found."
        return out
    s0 = metrics.loc[metrics["scenario_id"] == "S0"].iloc[0]
    p2 = p2_row.iloc[0]
    p2_max_accum = float(p2["geo_max_cumulative_rain_mm"])
    p3_max_accum = float(s0["max_accum_rain_mm"])
    loc_shift = haversine_km(
        float(p2["geo_max_cumulative_rain_lon"]),
        float(p2["geo_max_cumulative_rain_lat"]),
        float(s0["max_accum_lon"]),
        float(s0["max_accum_lat"]),
    )
    p2_d10 = float(p2["geo_max_duration10_h"])
    p3_d10 = float(s0["geo_D10_max_h"])
    p2_area10 = float(pd.to_numeric(p2_ts["geo_area_10_km2"], errors="coerce").max())
    p3_area10 = float(s0["max_area10_km2"])
    p2_volume = float(pd.to_numeric(p2_ts["geo_volume_proxy_mm_km2"], errors="coerce").sum())
    p3_volume = float(s0["total_event_rain_volume_index"])
    accum_rel = abs(p3_max_accum - p2_max_accum) / max(abs(p2_max_accum), EPS)
    d10_abs = abs(p3_d10 - p2_d10)
    area_rel = abs(p3_area10 - p2_area10) / max(abs(p2_area10), EPS)
    volume_rel = abs(p3_volume - p2_volume) / max(abs(p2_volume), EPS)
    if accum_rel <= 0.05 and d10_abs <= 3.0 and area_rel <= 0.10 and volume_rel <= 0.10:
        status = "PASS"
        note = "S0 event metrics are close to the Problem-2 KONG-REY geographic baseline."
    elif accum_rel <= 0.20 and d10_abs <= 10.0 and area_rel <= 0.25 and volume_rel <= 0.25:
        status = "WARNING-but-usable"
        note = "S0 differs from the Problem-2 baseline but remains usable; Step-2 already recorded non-identical S0 fields."
    else:
        status = "WARNING"
        note = "S0 differs clearly from the Problem-2 baseline; use the unified Problem-3 S0 as the scenario control."
    out.update(
        {
            "status": status,
            "note": note,
            "problem2_max_accum_rain_mm": p2_max_accum,
            "problem3_s0_max_accum_rain_mm": p3_max_accum,
            "max_accum_abs_diff_mm": float(abs(p3_max_accum - p2_max_accum)),
            "max_accum_location_shift_km": float(loc_shift),
            "problem2_geo_D10_max_h": p2_d10,
            "problem3_s0_geo_D10_max_h": p3_d10,
            "geo_D10_abs_diff_h": float(d10_abs),
            "problem2_max_area10_km2": p2_area10,
            "problem3_s0_max_area10_km2": p3_area10,
            "max_area10_rel_diff_pct": pct_change(p3_area10, p2_area10),
            "problem2_volume_index": p2_volume,
            "problem3_s0_volume_index": p3_volume,
            "volume_rel_diff_pct": pct_change(p3_volume, p2_volume),
        }
    )
    return out


def build_step3_qc(
    results: Mapping[str, Mapping[str, object]],
    geo: Mapping[str, np.ndarray],
    generation_qc: pd.DataFrame,
    baseline: Mapping[str, object],
    figure_paths: Sequence[Path],
) -> pd.DataFrame:
    area_valid = bool(np.isfinite(geo["area_1d"]).all() and np.all(np.asarray(geo["area_1d"]) > 0.0))
    expected_figure_count = 15
    all_figures_ok = len(figure_paths) >= expected_figure_count and all(Path(p).exists() for p in figure_paths)
    gen_qc = generation_qc.set_index("scenario_id").to_dict("index")
    rows: List[Dict[str, object]] = []
    for sid in SCENARIO_ORDER:
        result = results[sid]
        accum = np.asarray(result["accum_rain_mm"], dtype=np.float64)
        d10 = np.asarray(result["duration10_h"], dtype=np.float64)
        d20 = np.asarray(result["duration20_h"], dtype=np.float64)
        invalid_accum = int(np.count_nonzero(np.isnan(accum)) + np.count_nonzero(np.isinf(accum)))
        negative_accum = int(np.count_nonzero(np.isfinite(accum) & (accum < 0.0)))
        accum_all_zero = bool(np.nanmax(accum) <= 0.0)
        dur_all_zero = bool(np.nanmax(d10) <= 0.0 and np.nanmax(d20) <= 0.0)
        notes: List[str] = []
        level = "PASS"
        if invalid_accum > 0 or negative_accum > 0:
            level = "FAIL"
            notes.append("accumulation contains invalid or negative values")
        if accum.shape != np.asarray(geo["lon2d"]).shape or d10.shape != accum.shape:
            level = "FAIL"
            notes.append("geographic array shape mismatch")
        if accum_all_zero or dur_all_zero:
            level = "FAIL"
            notes.append("accumulation or duration result is all zero")
        if not area_valid:
            level = "FAIL"
            notes.append("latitude-corrected grid area is invalid")
        if not all_figures_ok:
            level = "FAIL"
            notes.append("required figures were not all generated")
        inherited = gen_qc.get(sid, {}).get("qc_level", "")
        inherited_note = gen_qc.get(sid, {}).get("qc_note", "")
        if level != "FAIL":
            if str(inherited).upper() == "WARNING":
                level = "WARNING"
                notes.append(f"step2_qc_warning:{inherited_note}")
            if sid == "S0" and str(baseline.get("status")) not in {"PASS", "not_found"}:
                level = "WARNING"
                notes.append(f"baseline_consistency:{baseline.get('status')}")
        rows.append(
            {
                "scenario_id": sid,
                "n_timesteps": int(len(result["track"])),
                "accum_shape": str(accum.shape),
                "duration_shape": str(d10.shape),
                "nan_count_accum": int(np.count_nonzero(np.isnan(accum))),
                "inf_count_accum": int(np.count_nonzero(np.isinf(accum))),
                "negative_count_accum": negative_accum,
                "max_accum_rain_mm": float(np.nanmax(accum)),
                "max_duration10_h": float(np.nanmax(d10)),
                "area_grid_valid": area_valid,
                "same_colorbar_ready": all_figures_ok,
                "geographic_projection_status": "completed_common_0.1deg_grid",
                "baseline_consistency_status": str(baseline.get("status")) if sid == "S0" else "not_applicable",
                "qc_level": level,
                "qc_note": "; ".join(notes) if notes else "Step-3 metrics quality checks passed.",
            }
        )
    return pd.DataFrame(rows)


def add_interpretation_and_qc(metrics: pd.DataFrame, qc: pd.DataFrame, rel_changes: pd.DataFrame) -> pd.DataFrame:
    qc_by_sid = qc.set_index("scenario_id")
    rel_by_sid = rel_changes.set_index("scenario_id")
    out = metrics.copy()
    notes = []
    levels = []
    for _, row in out.iterrows():
        sid = str(row["scenario_id"])
        levels.append(qc_by_sid.loc[sid, "qc_level"])
        if sid == "S0":
            note = "Baseline control scenario for all relative changes."
        elif sid == "S1":
            note = f"Intensity enhancement: max rain rate delta {rel_by_sid.loc[sid, 'delta_max_rain_rate_pct']:.1f}%."
        elif sid == "S2":
            note = f"Near-coast path shift: accum>=100 mm IoU {row['IoU_accum_ge_100mm_vs_S0']:.2f}."
        elif sid == "S3":
            note = f"Nearshore segment shift: centroid shift {row['rainfall_centroid_shift_km_vs_S0']:.1f} km."
        elif sid == "S4":
            note = f"Slower translation: geo D10 delta {rel_by_sid.loc[sid, 'delta_geo_D10_max_pct']:.1f}%."
        else:
            note = f"Compound scenario: volume index delta {rel_by_sid.loc[sid, 'delta_total_event_rain_volume_pct']:.1f}%."
        notes.append(note)
    out["qc_level"] = levels
    out["interpretation_note"] = notes
    return out


