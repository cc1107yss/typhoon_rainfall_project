def cartopy_available(problem2_geo_module) -> bool:
    try:
        return bool(problem2_geo_module.cartopy_local_features_available())
    except Exception:
        return False


def setup_axes(fig, extent: Sequence[float], use_cartopy: bool, problem2_geo_module):
    if use_cartopy:
        try:
            return problem2_geo_module.setup_geo_axes(fig, extent, True)
        except Exception:
            pass
    ax = fig.add_subplot(1, 1, 1)
    ax.set_xlim(extent[0], extent[1])
    ax.set_ylim(extent[2], extent[3])
    ax.set_xlabel("longitude")
    ax.set_ylabel("latitude")
    ax.grid(True, linewidth=0.35, linestyle="--", alpha=0.35)
    return ax, None


def plot_track_and_centroid(ax, track: pd.DataFrame, centroid_lon: float, centroid_lat: float, transform=None) -> None:
    kwargs = {"transform": transform} if transform is not None else {}
    lon = pd.to_numeric(track["lon_180"], errors="coerce").to_numpy(dtype=np.float64)
    lat = pd.to_numeric(track["lat"], errors="coerce").to_numpy(dtype=np.float64)
    ax.plot(lon, lat, color="black", linewidth=1.2, alpha=0.85, zorder=5, **kwargs)
    ax.scatter(lon[0], lat[0], marker="s", s=42, color="#2ca25f", edgecolor="black", linewidth=0.4, zorder=6, **kwargs)
    ax.scatter(lon[-1], lat[-1], marker="X", s=48, color="#de2d26", edgecolor="black", linewidth=0.4, zorder=6, **kwargs)
    if np.isfinite(centroid_lon) and np.isfinite(centroid_lat):
        ax.scatter(
            centroid_lon,
            centroid_lat,
            marker="*",
            s=115,
            color="#ffbf00",
            edgecolor="black",
            linewidth=0.55,
            zorder=7,
            **kwargs,
        )


def make_map_figures(
    results: Mapping[str, Mapping[str, object]],
    metrics: pd.DataFrame,
    geo: Mapping[str, np.ndarray],
    problem2_geo_module,
) -> List[Path]:
    PROBLEM3_FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    lon_1d = np.asarray(geo["lon_1d"], dtype=np.float64)
    lat_1d = np.asarray(geo["lat_1d"], dtype=np.float64)
