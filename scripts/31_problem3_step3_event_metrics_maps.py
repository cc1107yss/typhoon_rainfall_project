def brief_conclusion(row: pd.Series, rel_row: pd.Series) -> str:
    sid = str(row["scenario_id"])
    if sid == "S0":
        return "直接复用问题二 KONG-REY calibrated/geographic 基准。"
    if sid == "S1":
        return f"强度增强主要抬升雨强尾部，P99 变化 {rel_row['delta_max_p99_pct']:.1f}%."
    if sid == "S2":
        return f"路径近岸改变落区重叠，累计雨区 IoU 为 {row['IoU_accum_ge_100mm_vs_S0']:.2f}."
    if sid == "S3":
        return f"近岸段偏移主要转移沿海影响带，质心偏移 {row['rainfall_centroid_shift_km_vs_S0']:.1f} km."
