def latex_escape(value: object) -> str:
    text = "" if pd.isna(value) else str(value)
    text = text.replace("\\", "<<<BACKSLASH>>>")
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    text = text.replace("<<<BACKSLASH>>>", r"\textbackslash{}")
    return text


